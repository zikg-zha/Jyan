/* ---------- 私有工具函数 ---------- */

-- 业务错误：hint 携带类 HTTP 状态码，detail 可带 JSON 数据（如 409 时的最新订单）
create or replace function private.fail(p_status int, p_message text, p_data jsonb default null)
returns void language plpgsql set search_path = '' as $$
begin
  raise exception using
    message = p_message,
    hint = 'jiayan:' || p_status,
    detail = coalesce(p_data::text, '');
end $$;

create or replace function private.me() returns public.members
language plpgsql stable set search_path = '' as $$
declare m public.members;
begin
  select mm.* into m from private.member_sessions s
  join public.members mm on mm.id = s.member_id
  where s.user_id = auth.uid();
  if m.id is null then
    perform private.fail(401, '请先登录');
  end if;
  return m;
end $$;

create or replace function private.segment_of(p_status text) returns text
language sql immutable set search_path = '' as $$
  select case p_status when '已完成' then '已完成' when '已取消' then '已取消' else '进行中' end
$$;

create or replace function private.segment_statuses(p_segment text) returns text[]
language sql immutable set search_path = '' as $$
  select case p_segment
    when '进行中' then array['待接单', '已接单', '采购中', '准备中', '烹饪中']
    when '已完成' then array['已完成']
    when '已取消' then array['已取消']
  end
$$;

-- 接单后必须按序推进
create or replace function private.next_status(p_status text) returns text
language sql immutable set search_path = '' as $$
  select case p_status
    when '待接单' then '已接单'
    when '已接单' then '采购中'
    when '采购中' then '准备中'
    when '准备中' then '烹饪中'
    when '烹饪中' then '已完成'
  end
$$;

-- 状态流转校验：合法返回 null，否则返回提示文案
create or replace function private.can_transition(p_from text, p_to text) returns text
language sql immutable set search_path = '' as $$
  select case
    when p_to is null or p_to not in ('待接单', '已接单', '采购中', '准备中', '烹饪中', '已完成', '已取消')
      then '未知的订单状态'
    when p_from in ('已完成', '已取消') then '订单已结束，不能再变更状态'
    when p_to = '已取消' then null
    when p_from = '待接单' then case when p_to = '已接单' then null else '订单还未被接单，请先接单' end
    when p_to = private.next_status(p_from) then null
    else '请按顺序更新状态'
  end
$$;

-- 客户端按本地时区算好用餐日期，这里只做格式校验，非法时回落到北京时间今天
create or replace function private.clean_date(p_date text) returns date
language plpgsql stable set search_path = '' as $$
begin
  if p_date ~ '^\d{4}-\d{2}-\d{2}$' then
    return p_date::date;
  end if;
  return (now() at time zone 'Asia/Shanghai')::date;
exception when others then
  return (now() at time zone 'Asia/Shanghai')::date;
end $$;

-- 只接受 http(s) 图片地址，防止 javascript: 等协议
create or replace function private.clean_url(p_url text) returns text
language sql immutable set search_path = '' as $$
  select case when btrim(coalesce(p_url, '')) ~* '^https?://' and length(btrim(p_url)) <= 1000
    then btrim(p_url) else '' end
$$;

create or replace function private.clean_icon(p_icon text) returns text
language sql immutable set search_path = '' as $$
  select case when coalesce(p_icon, '') ~ '^fa-[a-z0-9-]{1,40}$' then p_icon else 'fa-utensils' end
$$;

-- jsonb 数组 → 去空白、去空项的字符串数组
create or replace function private.clean_list(p jsonb) returns jsonb
language sql immutable set search_path = '' as $$
  select coalesce(jsonb_agg(v order by n), '[]'::jsonb)
  from (
    select btrim(x) as v, n
    from jsonb_array_elements_text(case when jsonb_typeof(p) = 'array' then p else '[]'::jsonb end)
      with ordinality as t(x, n)
  ) s
  where v <> ''
$$;

-- 与原 Math.max(1, Number(x) || 默认值) 一致
create or replace function private.to_int(p jsonb, p_default int) returns int
language plpgsql immutable set search_path = '' as $$
declare n numeric;
begin
  if p is null or jsonb_typeof(p) not in ('number', 'string') then
    return p_default;
  end if;
  if btrim(p #>> '{}') !~ '^-?\d+(\.\d+)?$' then
    return p_default;
  end if;
  n := (p #>> '{}')::numeric;
  if n = 0 then
    return p_default;
  end if;
  return greatest(1, least(100000, trunc(n)))::int;
end $$;

