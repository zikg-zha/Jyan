-- 入参校验与清洗：名称、分类、至少 3 步做法
create or replace function private.clean_dish(p jsonb) returns jsonb
language plpgsql stable set search_path = '' as $$
declare
  v_name     text := btrim(coalesce(p->>'name', ''));
  v_category text := btrim(coalesce(p->>'category', ''));
  v_steps    jsonb;
  v_ings     jsonb;
begin
  if v_name = '' or v_category = '' then
    perform private.fail(400, '请填写菜品名称和分类');
  end if;
  if v_category not in ('荤菜', '素菜', '汤', '主食', '凉菜') then
    perform private.fail(400, '菜品分类不正确');
  end if;
  if length(v_name) > 40 then
    perform private.fail(400, '菜品名称最多 40 个字');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'title', coalesce(nullif(btrim(coalesce(s->>'title', '')), ''), '步骤 ' || rn),
      'desc',  btrim(coalesce(s->>'desc', '')),
      'photo', private.clean_url(s->>'photo')) order by rn), '[]'::jsonb)
  into v_steps
  from (
    select s, row_number() over (order by n) as rn
    from jsonb_array_elements(case when jsonb_typeof(p->'steps') = 'array' then p->'steps' else '[]'::jsonb end)
      with ordinality as t(s, n)
    where jsonb_typeof(s) = 'object'
      and btrim(coalesce(nullif(s->>'desc', ''), s->>'title', '')) <> ''
  ) x;
  if jsonb_array_length(v_steps) < 3 then
    perform private.fail(400, '做法至少需要 3 步');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'name', btrim(i->>'name'),
      'amount', btrim(coalesce(i->>'amount', '')),
      'unit', btrim(coalesce(i->>'unit', ''))) order by n), '[]'::jsonb)
  into v_ings
  from jsonb_array_elements(case when jsonb_typeof(p->'ingredients') = 'array'
                                 then p->'ingredients' else '[]'::jsonb end)
    with ordinality as t(i, n)
  where jsonb_typeof(i) = 'object' and btrim(coalesce(i->>'name', '')) <> '';

  return jsonb_build_object(
    'name', v_name,
    'category', v_category,
    'difficulty', case when p->>'difficulty' in ('简单', '中等', '困难') then p->>'difficulty' else '简单' end,
    'duration', private.to_int(p->'duration', 30),
    'servings', private.to_int(p->'servings', 2),
    'cover_url', private.clean_url(p->>'cover_url'),
    'icon', private.clean_icon(p->>'icon'),
    'ingredients', v_ings,
    'steps', v_steps);
end $$;

