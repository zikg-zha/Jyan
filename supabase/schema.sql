-- 家宴 · Supabase 数据库结构（表 / 权限 / 业务函数）
-- 用法：Supabase 控制台 → SQL Editor → 粘贴整个文件 → Run。可重复执行。
-- 安全模型：
--   · 前端只持有 anon key；所有写操作走 security definer 函数，函数内校验身份与业务规则
--   · 表只开放 select，并由 RLS 按「家庭」隔离；密码哈希、会话等放在不对外暴露的 private schema

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
create schema if not exists private;

/* ---------- 表 ---------- */

create table if not exists public.families (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  invite_code text        not null unique,
  channel_key uuid        not null default gen_random_uuid(),  -- 实时频道名，避免被猜测
  created_at  timestamptz not null default now()
);

create table if not exists public.members (
  id          bigint generated by default as identity primary key,
  family_id   bigint      not null references public.families(id) on delete cascade,
  name        text        not null,
  avatar_text text        not null,
  role        text        not null default 'member',   -- admin | member
  taboos      jsonb       not null default '[]',        -- 忌口食材
  specialties jsonb       not null default '[]',        -- 擅长菜品
  preference  text        not null default '',
  last_seen   timestamptz,
  created_at  timestamptz not null default now(),
  unique (family_id, name)
);

create table if not exists public.dishes (
  id          bigint generated by default as identity primary key,
  family_id   bigint      not null references public.families(id) on delete cascade,
  name        text        not null,
  category    text        not null,
  difficulty  text        not null default '简单',
  duration    integer     not null default 30,
  servings    integer     not null default 2,
  cover_url   text        not null default '',
  icon        text        not null default 'fa-utensils',
  ingredients jsonb       not null default '[]',        -- [{name,amount,unit}]
  steps       jsonb       not null default '[]',        -- [{title,desc,photo}]，至少 3 步
  order_count integer     not null default 0,
  created_by  bigint      references public.members(id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (family_id, name)
);
create table if not exists public.orders (
  id           bigint generated by default as identity primary key,
  family_id    bigint      not null references public.families(id) on delete cascade,
  creator_id   bigint      not null references public.members(id) on delete cascade,
  taker_id     bigint      references public.members(id) on delete set null,
  status       text        not null default '待接单',
  meal_time    text        not null,
  meal_date    date        not null,
  people       integer     not null default 2,
  eat_for      text        not null default '',
  note         text        not null default '',
  version      integer     not null default 1,          -- 乐观锁，防异地并发冲突
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.order_dishes (
  id       bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  dish_id  bigint references public.dishes(id) on delete set null,
  name     text   not null,
  icon     text   not null default 'fa-utensils'
);

create table if not exists public.order_collaborators (
  order_id  bigint      not null references public.orders(id) on delete cascade,
  member_id bigint      not null references public.members(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (order_id, member_id)
);

create table if not exists public.order_progress (
  id         bigint generated by default as identity primary key,
  order_id   bigint      not null references public.orders(id) on delete cascade,
  status     text        not null,
  member_id  bigint      references public.members(id) on delete set null,
  photo_url  text        not null default '',
  remark     text        not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id         bigint generated by default as identity primary key,
  family_id  bigint      not null references public.families(id) on delete cascade,
  member_id  bigint      not null references public.members(id) on delete cascade,
  order_id   bigint      references public.orders(id) on delete cascade,
  type       text        not null,
  title      text        not null,
  body       text        not null default '',
  icon       text        not null default 'fa-bell',
  icon_color text        not null default '#FA6400',
  is_read    boolean     not null default false,
  created_at timestamptz not null default now()
);

-- 私有表：密码哈希 / 设备会话 / 登录限流，前端无任何访问权限
create table if not exists private.member_secrets (
  member_id     bigint primary key references public.members(id) on delete cascade,
  password_hash text   not null
);

-- 每台设备一个 Supabase 匿名用户，登录成功后绑定到家庭成员
create table if not exists private.member_sessions (
  user_id    uuid        primary key references auth.users(id) on delete cascade,
  member_id  bigint      not null references public.members(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists private.login_attempts (
  id         bigint generated by default as identity primary key,
  key        text        not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_family_status on public.orders(family_id, status);
create index if not exists idx_orders_family_date   on public.orders(family_id, meal_date);
create index if not exists idx_dishes_family_cat    on public.dishes(family_id, category);
create index if not exists idx_order_dishes_order   on public.order_dishes(order_id);
create index if not exists idx_progress_order       on public.order_progress(order_id, id);
create index if not exists idx_collab_member        on public.order_collaborators(member_id);
create index if not exists idx_notif_member         on public.notifications(member_id, is_read, id desc);
create index if not exists idx_sessions_member      on private.member_sessions(member_id);
create index if not exists idx_login_attempts       on private.login_attempts(key, created_at);

/* ---------- 身份（RLS 使用） ---------- */

create or replace function public.current_member_id() returns bigint
language sql stable security definer set search_path = '' as $$
  select s.member_id from private.member_sessions s where s.user_id = auth.uid()
$$;

create or replace function public.current_family_id() returns bigint
language sql stable security definer set search_path = '' as $$
  select m.family_id from private.member_sessions s
  join public.members m on m.id = s.member_id
  where s.user_id = auth.uid()
$$;

/* ---------- 权限：表只读 + RLS 家庭隔离 ---------- */

revoke all on schema private from public, anon, authenticated;
revoke all on all tables in schema private from public, anon, authenticated;

revoke all on all tables in schema public from anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select on public.families, public.members, public.dishes, public.orders,
  public.order_dishes, public.order_collaborators, public.order_progress,
  public.notifications to authenticated;

alter table public.families            enable row level security;
alter table public.members             enable row level security;
alter table public.dishes              enable row level security;
alter table public.orders              enable row level security;
alter table public.order_dishes        enable row level security;
alter table public.order_collaborators enable row level security;
alter table public.order_progress      enable row level security;
alter table public.notifications       enable row level security;
alter table private.member_secrets     enable row level security;
alter table private.member_sessions    enable row level security;
alter table private.login_attempts     enable row level security;

drop policy if exists family_read on public.families;
create policy family_read on public.families for select to authenticated
  using (id = (select public.current_family_id()));

drop policy if exists family_read on public.members;
create policy family_read on public.members for select to authenticated
  using (family_id = (select public.current_family_id()));

drop policy if exists family_read on public.dishes;
create policy family_read on public.dishes for select to authenticated
  using (family_id = (select public.current_family_id()));

drop policy if exists family_read on public.orders;
create policy family_read on public.orders for select to authenticated
  using (family_id = (select public.current_family_id()));

drop policy if exists family_read on public.order_dishes;
create policy family_read on public.order_dishes for select to authenticated
  using (exists (select 1 from public.orders o
    where o.id = order_id and o.family_id = (select public.current_family_id())));

drop policy if exists family_read on public.order_collaborators;
create policy family_read on public.order_collaborators for select to authenticated
  using (exists (select 1 from public.orders o
    where o.id = order_id and o.family_id = (select public.current_family_id())));

drop policy if exists family_read on public.order_progress;
create policy family_read on public.order_progress for select to authenticated
  using (exists (select 1 from public.orders o
    where o.id = order_id and o.family_id = (select public.current_family_id())));

drop policy if exists own_read on public.notifications;
create policy own_read on public.notifications for select to authenticated
  using (member_id = (select public.current_member_id()));

