create or replace function private.order_json(p_id bigint, p_with_progress boolean default false)
returns jsonb language plpgsql stable set search_path = '' as $$
declare
  o public.orders;
  c public.members;
  t public.members;
  res jsonb;
begin
  select * into o from public.orders where id = p_id;
  if o.id is null then
    return null;
  end if;
  select * into c from public.members where id = o.creator_id;
  select * into t from public.members where id = o.taker_id;

  res := jsonb_build_object(
    'id', o.id,
    'status', o.status,
    'segment', private.segment_of(o.status),
    'meal_time', o.meal_time,
    'meal_date', o.meal_date,
    'people', o.people,
    'eat_for', o.eat_for,
    'note', o.note,
    'version', o.version,
    'created_at', o.created_at,
    'updated_at', o.updated_at,
    'completed_at', o.completed_at,
    'creator', jsonb_build_object('id', c.id, 'name', c.name, 'avatar_text', c.avatar_text),
    'taker', case when t.id is null then null
             else jsonb_build_object('id', t.id, 'name', t.name, 'avatar_text', t.avatar_text) end,
    'dishes', coalesce((
      select jsonb_agg(jsonb_build_object('dish_id', od.dish_id, 'name', od.name, 'icon', od.icon) order by od.id)
      from public.order_dishes od where od.order_id = o.id), '[]'::jsonb),
    'collaborators', coalesce((
      select jsonb_agg(jsonb_build_object('id', m.id, 'name', m.name, 'avatar_text', m.avatar_text)
                       order by oc.joined_at, m.id)
      from public.order_collaborators oc join public.members m on m.id = oc.member_id
      where oc.order_id = o.id), '[]'::jsonb),
    'next_status', private.next_status(o.status));

  if p_with_progress then
    res := res || jsonb_build_object('progress', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', p.id, 'status', p.status, 'photo_url', p.photo_url, 'remark', p.remark,
        'created_at', p.created_at, 'member_id', p.member_id, 'member_name', m.name) order by p.id)
      from public.order_progress p left join public.members m on m.id = p.member_id
      where p.order_id = o.id), '[]'::jsonb));
  end if;
  return res;
end $$;

/* ---------- 通知 ---------- */

-- 给指定成员发站内消息（去重、排除触发者、只发给本家庭成员）；Realtime 负责即时推送
create or replace function private.notify(
  p_family bigint, p_members bigint[], p_exclude bigint, p_order bigint,
  p_type text, p_title text, p_body text default ''
) returns void language plpgsql set search_path = '' as $$
declare
  v_icon  text;
  v_color text;
begin
  select i, c into v_icon, v_color from (values
    ('new_order', 'fa-utensils',   '#FA6400'),
    ('taken',     'fa-hand-paper', '#1F69FF'),
    ('assigned',  'fa-user-check', '#1F69FF'),
    ('status',    'fa-fire',       '#FA830C'),
    ('done',      'fa-check',      '#12B312'),
    ('cancel',    'fa-ban',        '#8c8c8c')
  ) as s(k, i, c) where k = p_type;

  insert into public.notifications (family_id, member_id, order_id, type, title, body, icon, icon_color)
  select p_family, x.mid, p_order, p_type, p_title, coalesce(p_body, ''),
         coalesce(v_icon, 'fa-bell'), coalesce(v_color, '#FA6400')
  from (select distinct unnest(p_members) as mid) x
  where x.mid is not null
    and x.mid is distinct from p_exclude
    and exists (select 1 from public.members m where m.id = x.mid and m.family_id = p_family)
  order by x.mid;
end $$;

-- 订单相关人：下单人 + 接单人 + 协作人
create or replace function private.stakeholders(p_order bigint) returns bigint[]
language sql stable set search_path = '' as $$
  select coalesce(array_agg(distinct x) filter (where x is not null), '{}')
  from (
    select creator_id as x from public.orders where id = p_order
    union all select taker_id from public.orders where id = p_order
    union all select member_id from public.order_collaborators where order_id = p_order
  ) s
$$;

create or replace function private.family_member_ids(p_family bigint) returns bigint[]
language sql stable set search_path = '' as $$
  select coalesce(array_agg(id order by id), '{}') from public.members where family_id = p_family
$$;

