  end if;
  if o.status in ('已完成', '已取消') then
    perform private.fail(400, '订单已结束');
  end if;
  if o.taker_id = me.id then
    perform private.fail(400, '你已是该订单接单人');
  end if;

  insert into public.order_collaborators (order_id, member_id) values (p_id, me.id)
  on conflict do nothing;
  update public.orders set updated_at = now() where id = p_id;  -- 触发实时同步

  perform private.notify(me.family_id, private.stakeholders(p_id), me.id, p_id, 'taken',
    format('%s 加入协作「%s」', me.name, private.dish_names(p_id)), '');
  return private.order_json(p_id, true);
end $$;

-- 进度更新：乐观锁 + 权限 + 按序流转
create or replace function public.update_status(
  p_id bigint, p_status text, p_photo_url text default '', p_remark text default '', p_version int default null
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  me       public.members := private.me();
  o        public.orders;
  v_to     text := btrim(coalesce(p_status, ''));
  v_remark text := btrim(coalesce(p_remark, ''));
  v_photo  text := private.clean_url(p_photo_url);
  v_err    text;
  v_names  text;
begin
  select * into o from public.orders where id = p_id and family_id = me.family_id for update;
  if o.id is null then
    perform private.fail(404, '订单不存在');
  end if;
  if coalesce(p_version, 0) <> 0 and p_version <> o.version then
    perform private.fail(409, '订单已被其他家人更新，已为你同步最新状态', private.order_json(p_id, true));
  end if;
  if not coalesce(o.creator_id = me.id or o.taker_id = me.id
      or exists (select 1 from public.order_collaborators where order_id = p_id and member_id = me.id), false) then
    perform private.fail(403, '只有接单人、协作人或下单人可以更新进度');
  end if;
  v_err := private.can_transition(o.status, v_to);
  if v_err is not null then
    perform private.fail(400, v_err);
  end if;

  update public.orders set status = v_to, version = version + 1, updated_at = now(),
    completed_at = case when v_to = '已完成' then now() else completed_at end
  where id = p_id;
  insert into public.order_progress (order_id, status, member_id, photo_url, remark)
  values (p_id, v_to, me.id, v_photo, v_remark);

  v_names := private.dish_names(p_id);
  perform private.notify(me.family_id, private.stakeholders(p_id), me.id, p_id,
    case v_to when '已完成' then 'done' when '已取消' then 'cancel' else 'status' end,
    case when v_to = '已完成' then format('%s 完成了「%s」', me.name, v_names)
         else format('%s 把「%s」更新为 %s', me.name, v_names, v_to) end,
    case when v_remark <> '' then v_remark when v_photo <> '' then '附了一张过程照片' else '' end);
  return private.order_json(p_id, true);
end $$;

create or replace function public.cancel_order(p_id bigint, p_reason text default '') returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  me       public.members := private.me();
  o        public.orders;
  v_reason text := btrim(coalesce(p_reason, ''));
  v_err    text;
begin
  select * into o from public.orders where id = p_id and family_id = me.family_id for update;
  if o.id is null then
    perform private.fail(404, '订单不存在');
  end if;
  v_err := private.can_transition(o.status, '已取消');
  if v_err is not null then
    perform private.fail(400, v_err);
  end if;

  update public.orders set status = '已取消', version = version + 1, updated_at = now() where id = p_id;
  insert into public.order_progress (order_id, status, member_id, remark)
  values (p_id, '已取消', me.id, coalesce(nullif(v_reason, ''), '订单已取消'));

  perform private.notify(me.family_id, private.stakeholders(p_id), me.id, p_id, 'cancel',
    format('%s 取消了「%s」', me.name, private.dish_names(p_id)), v_reason);
  return private.order_json(p_id, true);
end $$;

/* ---------- 消息中心（F-005） ---------- */

create or replace function public.list_notifications(p_limit int default 50) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare me public.members := private.me();
begin
  return jsonb_build_object(
    'items', coalesce((
      select jsonb_agg(to_jsonb(n) - 'family_id' order by n.id desc)
      from (select * from public.notifications where member_id = me.id
            order by id desc limit greatest(1, least(200, coalesce(p_limit, 50)))) n), '[]'::jsonb),
    'unread', (select count(*) from public.notifications where member_id = me.id and not is_read));
end $$;

create or replace function public.unread_count() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare me public.members := private.me();
begin
  return jsonb_build_object('unread',
    (select count(*) from public.notifications where member_id = me.id and not is_read));
end $$;

create or replace function public.read_notification(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare me public.members := private.me();
begin
  update public.notifications set is_read = true where id = p_id and member_id = me.id;
  return jsonb_build_object('id', p_id);
end $$;

create or replace function public.read_all_notifications() returns jsonb
language plpgsql security definer set search_path = '' as $$
