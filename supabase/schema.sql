end $$;

/* ---------- 历史统计（F-009） ---------- */

create or replace function public.family_stats() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  me       public.members := private.me();
  v_contrib jsonb;
  v_max     int;
  v_total   int;
  v_done    int;
  v_cancel  int;
begin
  select coalesce(max(cnt), 0) into v_max from (
    select count(*) as cnt from public.orders
    where family_id = me.family_id and status = '已完成' and taker_id is not null group by taker_id) s;

  select coalesce(jsonb_agg(jsonb_build_object(
      'id', id, 'name', name, 'avatar_text', avatar_text, 'cook_count', cook_count,
      'percent', case when v_max > 0 then round(cook_count * 100.0 / v_max) else 0 end)
    order by cook_count desc, id), '[]'::jsonb)
  into v_contrib
  from (
    select m.id, m.name, m.avatar_text, count(o.id)::int as cook_count
    from public.members m
    left join public.orders o on o.taker_id = m.id and o.status = '已完成' and o.family_id = me.family_id
    where m.family_id = me.family_id
    group by m.id
  ) c;

  select count(*), count(*) filter (where status = '已完成'), count(*) filter (where status = '已取消')
  into v_total, v_done, v_cancel
  from public.orders where family_id = me.family_id;

  return jsonb_build_object(
    'contributors', v_contrib,
    'popular', coalesce((
      select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'category', category,
                                          'icon', icon, 'order_count', order_count)
                       order by order_count desc, id)
      from (select * from public.dishes where family_id = me.family_id and order_count > 0
            order by order_count desc, id limit 10) d), '[]'::jsonb),
    'pairs', coalesce((
      select jsonb_agg(jsonb_build_object('creator_name', creator_name, 'taker_name', taker_name,
                                          'dishes', dishes, 'times', times) order by times desc)
      from (
        select c.name as creator_name, t.name as taker_name,
               string_agg(od.name, '、' order by od.id) as dishes, count(distinct o.id)::int as times
        from public.orders o
        join public.members c on c.id = o.creator_id
        join public.members t on t.id = o.taker_id
        join public.order_dishes od on od.order_id = o.id
        where o.family_id = me.family_id and o.status = '已完成'
        group by o.creator_id, o.taker_id, c.name, t.name
        order by times desc limit 20
      ) p), '[]'::jsonb),
    'summary', jsonb_build_object(
      'total_orders', v_total,
      'done_orders', v_done,
      'canceled_orders', v_cancel,
      'dish_total', (select count(*) from public.dishes where family_id = me.family_id),
      'member_total', (select count(*) from public.members where family_id = me.family_id),
      'close_rate', case when v_total > 0 then round(v_done * 100.0 / v_total) else 0 end));
end $$;

