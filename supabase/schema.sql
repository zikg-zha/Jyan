-- 忌口检查（F-008）：食材与忌口双向包含即命中；只提醒，不阻止下单
create or replace function public.taboo_check(p_dish_ids bigint[], p_member_ids bigint[])
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  me       public.members := private.me();
  d        public.dishes;
  m        public.members;
  v_hits   jsonb;
  warnings jsonb := '[]'::jsonb;
begin
  if coalesce(cardinality(p_dish_ids), 0) = 0 or coalesce(cardinality(p_member_ids), 0) = 0 then
    return jsonb_build_object('warnings', warnings);
  end if;
  for d in select * from public.dishes
           where family_id = me.family_id and id = any(p_dish_ids) order by id loop
    for m in select * from public.members
             where family_id = me.family_id and id = any(p_member_ids) order by id loop
      select coalesce(jsonb_agg(tb order by first_n), '[]'::jsonb) into v_hits
      from (
        select tb, min(n) as first_n
        from (
          select btrim(x) as tb, n
          from jsonb_array_elements_text(m.taboos) with ordinality as t(x, n)
        ) s
        where tb <> '' and exists (
          select 1 from jsonb_array_elements(d.ingredients) i
          where strpos(coalesce(i->>'name', ''), tb) > 0 or strpos(tb, coalesce(i->>'name', '')) > 0)
        group by tb
      ) h;
      if jsonb_array_length(v_hits) > 0 then
        warnings := warnings || jsonb_build_array(jsonb_build_object(
          'dish_id', d.id, 'dish_name', d.name, 'member_id', m.id, 'member_name', m.name,
          'taboos', v_hits,
          'message', format('该菜品「%s」含%s，%s忌口。若是代别人点可忽略。', d.name,
            (select string_agg(e, '、' order by n) from jsonb_array_elements_text(v_hits)
               with ordinality as t(e, n)), m.name)));
      end if;
    end loop;
  end loop;
  return jsonb_build_object('warnings', warnings);
end $$;

