/* ---------- 登录与成员（F-007） ---------- */

-- 登录：家庭邀请码 + 成员名 + 密码，成功后把当前设备的匿名用户绑定到该成员
-- 失败不抛异常（否则限流记录会随事务回滚），返回 {ok:false, message}
create or replace function public.login(p_invite_code text, p_name text, p_password text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_uid    uuid := auth.uid();
  v_code   text := upper(btrim(coalesce(p_invite_code, '')));
  v_name   text := btrim(coalesce(p_name, ''));
  v_key    text;
  v_member public.members;
  v_hash   text;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'message', '连接已失效，请刷新页面后重试');
  end if;
  if v_code = '' or v_name = '' or coalesce(p_password, '') = '' then
    return jsonb_build_object('ok', false, 'message', '请填写家庭邀请码、成员名和密码');
  end if;
  v_key := 'm:' || v_code || ':' || v_name;

  -- 限流：同一成员 15 分钟 5 次，同一家庭 30 次，同一设备 20 次
  if (select count(*) from private.login_attempts
      where key = v_key and created_at > now() - interval '15 minutes') >= 5
     or (select count(*) from private.login_attempts
      where key = 'f:' || v_code and created_at > now() - interval '15 minutes') >= 30
     or (select count(*) from private.login_attempts
      where key = 'u:' || v_uid and created_at > now() - interval '15 minutes') >= 20 then
    return jsonb_build_object('ok', false, 'message', '尝试次数过多，请 15 分钟后再试');
  end if;

  select m.* into v_member from public.members m
  join public.families f on f.id = m.family_id
  where f.invite_code = v_code and m.name = v_name;
  if v_member.id is not null then
    select password_hash into v_hash from private.member_secrets where member_id = v_member.id;
  end if;

  if v_hash is null or v_hash <> extensions.crypt(p_password, v_hash) then
    insert into private.login_attempts (key)
      values (v_key), ('f:' || v_code), ('u:' || v_uid);
    return jsonb_build_object('ok', false, 'message', '邀请码、成员名或密码不正确');
  end if;

  delete from private.login_attempts where key = v_key;
  delete from private.login_attempts where created_at < now() - interval '1 day';

  insert into private.member_sessions (user_id, member_id) values (v_uid, v_member.id)
  on conflict (user_id) do update set member_id = excluded.member_id, created_at = now();
  update public.members set last_seen = now() where id = v_member.id;

  return jsonb_build_object('ok', true, 'data', private.session_json(v_member));
end $$;

