-- 列表与筛选；p_today 由客户端按本地时区传入
create or replace function public.list_orders(
  p_segment text default '进行中', p_scope text default '今日', p_relation text default '全部',
  p_creator_id bigint default null, p_taker_id bigint default null,
  p_date text default null, p_today text default null
) returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  me         public.members := private.me();
  v_started  timestamptz := clock_timestamp();
  v_statuses text[] := private.segment_statuses(p_segment);
  v_items    jsonb;
begin
  select coalesce(jsonb_agg(private.order_json(x.id) order by x.meal_date desc, x.id desc), '[]'::jsonb)
  into v_items
  from (
    select o.id, o.meal_date from public.orders o
    where o.family_id = me.family_id
      and (v_statuses is null or o.status = any(v_statuses))
      and (coalesce(p_scope, '今日') <> '今日' or o.meal_date = private.clean_date(p_today))
      and (coalesce(p_date, '') = '' or o.meal_date = private.clean_date(p_date))
      and (coalesce(p_relation, '全部') <> '我下单的' or o.creator_id = me.id)
      and (coalesce(p_relation, '全部') <> '我接单的' or o.taker_id = me.id
           or exists (select 1 from public.order_collaborators oc
                      where oc.order_id = o.id and oc.member_id = me.id))
      and (coalesce(p_creator_id, 0) = 0 or o.creator_id = p_creator_id)
      and (coalesce(p_taker_id, 0) = 0 or o.taker_id = p_taker_id)
    order by o.meal_date desc, o.id desc
    limit 200
  ) x;

  return jsonb_build_object(
    'items', v_items,
    'total', jsonb_array_length(v_items),
    'elapsed_ms', round((extract(epoch from clock_timestamp() - v_started) * 1000)::numeric, 1));
end $$;

