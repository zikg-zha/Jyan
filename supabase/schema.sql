-- 下单；指派家人时直接进入「已接单」
create or replace function public.create_order(
  p_dish_ids bigint[], p_meal_time text default '今天晚饭', p_meal_date text default null,
  p_people int default 2, p_note text default '', p_eat_for text default '', p_assignee_id bigint default null
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  me         public.members := private.me();
  v_meal     text := coalesce(nullif(btrim(coalesce(p_meal_time, '')), ''), '今天晚饭');
  v_people   int := greatest(1, least(100, coalesce(nullif(p_people, 0), 2)));
  v_assignee public.members;
  v_status   text;
  v_id       bigint;
  v_names    text;
  v_body     text;
begin
  if coalesce(cardinality(p_dish_ids), 0) = 0 then
    perform private.fail(400, '请至少选择一道菜');
  end if;
  if not exists (select 1 from public.dishes where family_id = me.family_id and id = any(p_dish_ids)) then
    perform private.fail(400, '所选菜品不存在，请重新选择');
  end if;
  if coalesce(p_assignee_id, 0) <> 0 then
    select * into v_assignee from public.members where id = p_assignee_id and family_id = me.family_id;
    if v_assignee.id is null then
      perform private.fail(400, '指派的家人不存在');
    end if;
  end if;
  v_status := case when v_assignee.id is null then '待接单' else '已接单' end;

  insert into public.orders (family_id, creator_id, taker_id, status, meal_time, meal_date,
                             people, eat_for, note)
  values (me.family_id, me.id, v_assignee.id, v_status, v_meal, private.clean_date(p_meal_date),
          v_people, btrim(coalesce(p_eat_for, '')), btrim(coalesce(p_note, '')))
  returning id into v_id;

  insert into public.order_dishes (order_id, dish_id, name, icon)
  select v_id, d.id, d.name, d.icon from public.dishes d
  where d.family_id = me.family_id and d.id = any(p_dish_ids) order by d.id;
  update public.dishes set order_count = order_count + 1
  where family_id = me.family_id and id = any(p_dish_ids);

  insert into public.order_progress (order_id, status, member_id, remark)
  values (v_id, v_status, me.id,
          case when v_assignee.id is null then '已发起点菜单' else '下单并指派给' || v_assignee.name end);

  v_names := private.dish_names(v_id);
  v_body := v_meal || ' · ' || v_people || '人用餐';
  perform private.notify(me.family_id, private.family_member_ids(me.family_id), me.id, v_id,
    'new_order', format('%s 发起点菜单「%s」', me.name, v_names), v_body);
  if v_assignee.id is not null and v_assignee.id <> me.id then
    perform private.notify(me.family_id, array[v_assignee.id], null, v_id,
      'assigned', format('%s 指派你做「%s」', me.name, v_names), v_body);
  end if;
  return private.order_json(v_id, true);
end $$;

-- 接单：先到先得，后到者自动转为协作
create or replace function public.take_order(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  me       public.members := private.me();
  o        public.orders;
  v_collab boolean := false;
  v_msg    text := '';
begin
  select * into o from public.orders where id = p_id and family_id = me.family_id for update;
  if o.id is null then
    perform private.fail(404, '订单不存在');
  end if;
  if o.status in ('已完成', '已取消') then
    perform private.fail(409, '订单已结束，无法接单');
  end if;

  if o.taker_id is not null and o.taker_id <> me.id then
    insert into public.order_collaborators (order_id, member_id) values (p_id, me.id)
    on conflict do nothing;
    update public.orders set updated_at = now() where id = p_id;
    v_collab := true;
    v_msg := '该订单已被接单，已把你加入协作';
  elsif o.taker_id is null then
    update public.orders set taker_id = me.id, status = '已接单', version = version + 1, updated_at = now()
    where id = p_id;
    insert into public.order_progress (order_id, status, member_id, remark)
    values (p_id, '已接单', me.id, '已接单');
  else
    -- 本来就是接单人：不改状态
    return jsonb_build_object('order', private.order_json(p_id, true),
                              'joined_as_collaborator', false, 'message', '');
  end if;

  perform private.notify(me.family_id, private.stakeholders(p_id), me.id, p_id, 'taken',
    case when v_collab then format('%s 加入协作「%s」', me.name, private.dish_names(p_id))
         else format('%s 接单了「%s」', me.name, private.dish_names(p_id)) end,
    case when v_collab then '多人协作进行中' else '开始准备啦' end);

  return jsonb_build_object('order', private.order_json(p_id, true),
                            'joined_as_collaborator', v_collab, 'message', v_msg);
end $$;

-- 下单人指派家人
create or replace function public.assign_order(p_id bigint, p_member_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  me       public.members := private.me();
  o        public.orders;
  v_target public.members;
begin
  select * into o from public.orders where id = p_id and family_id = me.family_id for update;
  if o.id is null then
    perform private.fail(404, '订单不存在');
  end if;
  if o.creator_id <> me.id then
    perform private.fail(403, '只有下单人可以指派');
  end if;
  if o.status in ('已完成', '已取消') then
    perform private.fail(400, '订单已结束，无法指派');
