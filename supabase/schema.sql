  if v_target.id is null then
    perform private.fail(400, '指派的家人不存在');
  end if;

  update public.orders set taker_id = v_target.id,
    status = case when status = '待接单' then '已接单' else status end,
    version = version + 1, updated_at = now()
  where id = p_id;
  insert into public.order_progress (order_id, status, member_id, remark)
  values (p_id, '已接单', me.id, '指派给' || v_target.name);

  perform private.notify(me.family_id, array[v_target.id], me.id, p_id, 'assigned',
    format('%s 指派你做「%s」', me.name, private.dish_names(p_id)),
    o.meal_time || ' · ' || o.people || '人用餐');
  return private.order_json(p_id, true);
end $$;

